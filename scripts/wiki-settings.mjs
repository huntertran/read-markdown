// Generates wiki/Settings.md from package.json `contributes.configuration`, so the wiki's settings reference
// cannot drift from what the extension declares. `--check` (CI) fails instead of writing when the file is stale.
//   node scripts/wiki-settings.mjs          # write wiki/Settings.md
//   node scripts/wiki-settings.mjs --check  # exit 1 if wiki/Settings.md is out of date
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const OUT = 'wiki/Settings.md';
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
const props = pkg.contributes.configuration.properties;
const restricted = new Set(pkg.capabilities?.untrustedWorkspaces?.restrictedConfigurations ?? []);

// Settings with a control in the ⚙ quick panel: the `key: '…'` entries of its SECTIONS.
const panelSource = readFileSync('webview/settingsPanel.ts', 'utf8');
const inPanel = new Set([...panelSource.matchAll(/\bkey:\s*'([\w.]+)'/g)].map((m) => `readMarkdown.${m[1]}`));

const GROUPS = {
  preview: 'Preview',
  nav: 'Quick navigation',
  theme: 'Theme',
  body: 'Body text',
  headings: 'Headings',
  customCss: 'Custom CSS',
  search: 'Search highlight sync',
  table: 'Tables',
  code: 'Code blocks',
  mermaid: 'Mermaid diagrams',
  sections: 'Sections',
  edit: 'Editing in the preview',
  changes: 'Changes against git',
  tasks: 'Task lists and agent progress',
  security: 'Security',
};

/** Inline text for a table cell: settings links become code, line breaks and pipes are escaped. */
function cell(text) {
  return String(text)
    .replace(/`#(readMarkdown\.[\w.]+)#`/g, '`$1`')
    .replace(/\|/g, '\\|')
    .replace(/\r?\n/g, '<br>');
}

function type(p) {
  if (p.type === 'array') return `${p.items?.type ?? 'any'}[]`;
  if (p.type === 'object') return 'object';
  return p.type;
}

function defaultValue(p) {
  const v = p.default;
  if (v === '') return '`""` (unset)';
  return `\`${JSON.stringify(v)}\``;
}

function details(p) {
  const parts = [cell(p.markdownDescription ?? p.description ?? '')];
  if (p.enum) {
    const values = p.enum.map((v, i) => {
      const d = p.enumDescriptions?.[i];
      return d ? `\`${v}\`: ${cell(d)}` : `\`${v}\``;
    });
    parts.push(`Values: ${values.join('<br>')}`);
  }
  const range = [];
  if (p.minimum !== undefined) range.push(`min ${p.minimum}`);
  if (p.maximum !== undefined) range.push(`max ${p.maximum}`);
  if (range.length) parts.push(`Range: ${range.join(', ')}.`);
  if (p.type === 'object' && p.properties) parts.push(`Keys: ${Object.keys(p.properties).map((k) => `\`${k}\``).join(', ')}.`);
  return parts.join('<br><br>');
}

const byGroup = new Map();
for (const [key, p] of Object.entries(props)) {
  const group = key.split('.')[1];
  if (!GROUPS[group]) throw new Error(`No wiki group for ${key}: add "${group}" to GROUPS in scripts/wiki-settings.mjs`);
  if (!byGroup.has(group)) byGroup.set(group, []);
  byGroup.get(group).push([key, p]);
}

const lines = [
  '<!-- Generated by scripts/wiki-settings.mjs from package.json. Do not edit: run `npm run wiki:settings`. -->',
  '',
  '# Settings',
  '',
  'Every setting lives under `readMarkdown.*`. Open the Settings UI (`Ctrl+,`) and search for "Read Markdown", or edit `settings.json`.',
  '',
  '- **⚙** marks a setting you can also change from the quick settings panel (⚙ in the preview toolbar). The panel writes to the most specific scope that already defines the setting (folder, workspace or user).',
  '- **🔒** marks a setting that workspace settings cannot change until you trust the workspace ([Security](Security)).',
  '- An invalid value falls back to the default, and a number out of range is clamped to it.',
  '',
  '## Contents',
  '',
  ...[...byGroup.keys()].map((g) => `- [${GROUPS[g]}](#${GROUPS[g].toLowerCase().replace(/[^\w\s-]/g, '').replace(/\s+/g, '-')})`),
  '',
];

for (const [group, entries] of byGroup) {
  lines.push(`## ${GROUPS[group]}`, '', '| Setting | Type | Default | Description |', '| --- | --- | --- | --- |');
  for (const [key, p] of entries) {
    const marks = [inPanel.has(key) ? '⚙' : '', restricted.has(key) ? '🔒' : ''].filter(Boolean).join(' ');
    lines.push(`| \`${key}\`${marks ? ` ${marks}` : ''} | ${type(p)} | ${defaultValue(p)} | ${details(p)} |`);
  }
  lines.push('');
}

lines.push(
  '## Example',
  '',
  '```json',
  '"readMarkdown.theme.preset": "sepia",',
  '"readMarkdown.body.fontFamily": "Georgia, serif",',
  '"readMarkdown.headings.colors": { "h1": "#8b4513", "h2": "#a0522d" },',
  '"readMarkdown.customCss.inline": ".rm-markdown p { text-align: justify; }"',
  '```',
  '',
  'More styling in [Custom CSS](Custom-CSS).',
  '',
);

const output = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== output) {
    console.error(`${OUT} is out of date: run \`npm run wiki:settings\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date.`);
} else {
  writeFileSync(OUT, output);
  console.log(`wrote ${OUT} (${Object.keys(props).length} settings)`);
}
